"""Where the sandbox lives and the fixed facts about the fake company ("Larkspur Goods")."""

from __future__ import annotations

import os
from dataclasses import dataclass
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
DBT_PROJECT_DIR = REPO_ROOT / "dbt_project"

SEED = 20260901
HISTORY_START = date(2026, 9, 1)  # first partition generated by `pia sandbox init`
HISTORY_DAYS = 30  # 2026-09-01 .. 2026-09-30 form the clean baseline
INCIDENT_DAY = date(2026, 10, 1)  # incidents are injected into the day after the baseline

# Event tables arrive as one landing file per day; products is a dimension delivered once.
EVENT_TABLES = ("customers", "orders", "order_items", "payments")
DIMENSION_TABLES = ("products",)
ALL_TABLES = DIMENSION_TABLES + EVENT_TABLES


@dataclass(frozen=True)
class SandboxPaths:
    root: Path

    @property
    def landing(self) -> Path:
        return self.root / "landing"

    @property
    def warehouse(self) -> Path:
        return self.root / "warehouse.duckdb"

    @property
    def dagster_home(self) -> Path:
        return self.root / "dagster_home"

    @property
    def logs(self) -> Path:
        return self.root / "logs"

    @property
    def pipeline_log(self) -> Path:
        return self.logs / "pipeline.log"

    @property
    def dbt_target(self) -> Path:
        return self.root / "dbt_target"

    @property
    def dbt_project(self) -> Path:
        """The sandbox's own copy of the dbt project, so a bad deploy can be simulated and reverted."""
        return self.root / "dbt_project"

    @property
    def ingest_config(self) -> Path:
        return self.root / "config" / "ingest.json"

    @property
    def upstream_changes(self) -> Path:
        """Persistent changes the upstream system has made to its exports (see upstream.py)."""
        return self.root / "upstream" / "changes.json"

    @property
    def snapshots(self) -> Path:
        return self.root.parent / "snapshots"

    def landing_file(self, table: str, day: date | None) -> Path:
        if day is None:
            return self.landing / table / f"{table}.csv"
        return self.landing / table / f"dt={day.isoformat()}" / f"{table}.csv"

    def ensure(self) -> None:
        for p in (self.landing, self.dagster_home, self.logs, self.dbt_target, self.ingest_config.parent):
            p.mkdir(parents=True, exist_ok=True)
        if not self.dbt_project.exists():
            install_dbt_project(self.dbt_project)


def install_dbt_project(dest: Path) -> None:
    """Copy the repo's dbt project (the "deployed" version) into a sandbox."""
    import shutil

    shutil.copytree(DBT_PROJECT_DIR, dest, ignore=shutil.ignore_patterns("target", "logs", ".user.yml"))


def default_paths() -> SandboxPaths:
    return SandboxPaths(Path(os.environ.get("PIA_SANDBOX", REPO_ROOT / "sandbox" / "state")).resolve())
